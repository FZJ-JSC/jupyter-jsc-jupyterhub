#!/usr/bin/env python3
"""Open a GitLab merge request for a pushed requirements-refresh branch.

Used by the scheduled ``update-requirements`` CI job. Reads the GitLab
credentials + API location from the standard CI environment variables
(``GL_TOKEN`` project access token with api scope, ``CI_API_V4_URL``,
``CI_PROJECT_ID``, ``CI_DEFAULT_BRANCH``) and takes the source branch as
argv[1].
"""
import json
import os
import sys
import urllib.request


def main() -> int:
    if len(sys.argv) != 2:
        print(f"usage: {sys.argv[0]} <source-branch>", file=sys.stderr)
        return 2
    branch = sys.argv[1]
    for var in ("GL_TOKEN", "CI_API_V4_URL", "CI_PROJECT_ID"):
        if not os.environ.get(var):
            print(f"error: environment variable {var} is required", file=sys.stderr)
            return 1

    url = (
        f"{os.environ['CI_API_V4_URL']}"
        f"/projects/{os.environ['CI_PROJECT_ID']}/merge_requests"
    )
    body = json.dumps({
        "source_branch": branch,
        "target_branch": os.environ.get("CI_DEFAULT_BRANCH", "main"),
        "title": "chore: refresh jjsc requirements section",
        "description": (
            "Automated update of the jjsc section of "
            "`requirements_upstream.txt` (generated by the scheduled "
            "`update-requirements` job).\n\n"
            "- Review the diff, merge when satisfied.\n"
            "- After merging, trigger the **tag-release** job on the "
            "default branch to create the next tag and build + push "
            "the images.\n"
            "- Reproduce locally with `./update-requirements.sh` (dry run)."
        ),
        "labels": ["requirements-update"],
        "remove_source_branch": True,
    }).encode()
    req = urllib.request.Request(
        url,
        data=body,
        method="POST",
        headers={
            "Authorization": f"Bearer {os.environ['GL_TOKEN']}",
            "Content-Type": "application/json",
        },
    )
    data = json.loads(urllib.request.urlopen(req, timeout=30).read())
    print(f"created MR !{data['iid']}: {data['web_url']}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
